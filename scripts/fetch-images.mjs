// Downloads the marketing photos listed in scripts/images.manifest.json, crops each one
// around its focal point and writes AVIF + WebP at 480/960/1600 px wide to
// public/images/marketing/. Also writes the blur placeholders and sizes to
// src/components/marketing/imageData.ts, and public/images/CREDITS.md.
//
// Usage: npm run images   (or: node scripts/fetch-images.mjs)
// A photo that can't be downloaded (after retries and any fallbackUrls) is skipped and
// listed in `missingPhotos`; the site shows that slot's illustration instead.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(root, "public/images/marketing");
const dataFile = path.join(root, "src/components/marketing/imageData.ts");
const creditsFile = path.join(root, "public/images/CREDITS.md");
const WIDTHS = [480, 960, 1600];
const QUALITY = { avif: 55, webp: 60 };

const manifest = JSON.parse(await readFile(path.join(root, "scripts/images.manifest.json"), "utf8"));
await mkdir(outDir, { recursive: true });

async function download(url, tries = 3) {
  for (let i = 1; i <= tries; i++) {
    try {
      const res = await fetch(url, { headers: { "User-Agent": "HealingNet image pipeline" } });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      return Buffer.from(await res.arrayBuffer());
    } catch (err) {
      if (i === tries) throw err;
      await new Promise((r) => setTimeout(r, 1500 * i));
    }
  }
}

/** Largest crop with the given aspect ratio, centred on the focal point, kept inside the image. */
function cropBox(width, height, aspect, focal) {
  const [aw, ah] = aspect.split(":").map(Number);
  const ratio = aw / ah;
  let w = width;
  let h = Math.round(width / ratio);
  if (h > height) {
    h = height;
    w = Math.round(height * ratio);
  }
  const clamp = (v, max) => Math.max(0, Math.min(v, max));
  const left = clamp(Math.round(focal.x * width - w / 2), width - w);
  const top = clamp(Math.round(focal.y * height - h / 2), height - h);
  return { left, top, width: w, height: h };
}

const done = [];
const failed = [];

for (const img of manifest.images) {
  let source = null;
  for (const url of [img.downloadUrl, ...(img.fallbackUrls ?? [])]) {
    try {
      source = await download(url);
      break;
    } catch (err) {
      console.warn(`  ${img.id}: ${url} failed (${err.message})`);
    }
  }
  if (!source) {
    failed.push(img.id);
    continue;
  }

  const upright = await sharp(source).rotate().toBuffer();
  const meta = await sharp(upright).metadata();
  const box = cropBox(meta.width, meta.height, img.aspect, img.focal ?? { x: 0.5, y: 0.5 });
  const cropped = await sharp(upright).extract(box).toBuffer();

  for (const w of WIDTHS) {
    const resized = sharp(cropped).resize({ width: w, withoutEnlargement: true });
    await resized.clone().avif({ quality: QUALITY.avif, effort: 6 }).toFile(path.join(outDir, `${img.id}-${w}.avif`));
    await resized.clone().webp({ quality: QUALITY.webp }).toFile(path.join(outDir, `${img.id}-${w}.webp`));
  }

  const blur = await sharp(cropped).resize({ width: 20 }).blur(1).webp({ quality: 40 }).toBuffer();
  const [aw, ah] = img.aspect.split(":").map(Number);
  done.push({
    id: img.id,
    width: 1600,
    height: Math.round((1600 * ah) / aw),
    blur: `data:image/webp;base64,${blur.toString("base64")}`,
    alt: img.alt,
  });
  console.log(`ok ${img.id}`);
}

const data = `// Generated by scripts/fetch-images.mjs. Don't edit by hand; run \`npm run images\`.
import type { MarketingImage } from "./ResponsiveImage";

export interface MarketingPhoto extends MarketingImage {
  /** Default alt text: describes the scene, never a diagnosis. */
  alt: string;
}

export const photos: Record<string, MarketingPhoto | undefined> = {
${done.map((d) => `  "${d.id}": ${JSON.stringify(d)},`).join("\n")}
};

/** Photos that failed to download; their slots show an illustration instead. */
export const missingPhotos: string[] = ${JSON.stringify(failed)};
`;
await writeFile(dataFile, data);

const rows = manifest.images
  .filter((i) => !failed.includes(i.id))
  .map((i) => `| ${i.id} | [${i.author}](${i.authorUrl}) | [Photo page](${i.sourcePage}) | ${i.license} |`)
  .join("\n");
const credits = `# Image credits

Photos on the HealingNet public website, used under the
[Pexels License](https://www.pexels.com/license/) (free for commercial use).
Files in \`images/marketing/\` are named \`{id}-{480|960|1600}.{avif,webp}\`.

Generated by \`scripts/fetch-images.mjs\` from \`scripts/images.manifest.json\`.

| Image id | Photographer | Source | Licence |
|---|---|---|---|
${rows}

## Made in code (no photographer)

- \`/og-image.png\`, \`/favicon.svg\`, \`/apple-touch-icon.png\`, \`/icon-192.png\`, \`/icon-512.png\` and
  \`/images/logo-mark.png\`: generated by \`scripts/make-og.mjs\` from \`/logo.png\`.
- Illustrations: inline SVG React components in \`src/components/marketing/illustrations/\`.
`;
await writeFile(creditsFile, credits);

console.log(`\n${done.length} photos written, ${failed.length} failed${failed.length ? `: ${failed.join(", ")}` : ""}.`);
